export interface SheetConfig {
  sheetName: string;
  sheetCode: string;
  sheetPicks: number;
  description: string;
  category: 'common' | 'uncommon' | 'rare_mythic' | 'wildcard' | 'foil' | 'special_bonus' | 'land' | 'ancillary';
  rareOdds?: number; // 0.0 - 1.0 (e.g. 0.857 = 6/7 rare, 1/7 mythic)
  foilChance?: number; // 0.0 - 1.0
  isSpecialSheet?: boolean;
}

export interface BoosterVariation {
  boosterIndex: number;
  boosterWeight: number; // e.g. 75 / 100
  name: string;
  description: string;
  sheets: SheetConfig[];
}

