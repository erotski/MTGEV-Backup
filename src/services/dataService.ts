  /**
   * Loads Preconstructed Decks from /data/precon_decks.json with in-memory caching & request deduplication
   */
  public async getPreconDecks(): Promise<Record<string, any>> {
    if (this.preconDecksCache && Object.keys(this.preconDecksCache).length > 0) {
      return this.preconDecksCache;
    }
    if (this.preconDecksPromise) {
      return this.preconDecksPromise;
    }

    this.preconDecksPromise = (async () => {
      try {
        const response = await fetch('/data/precon_decks.json');
        if (response.ok) {
          const raw = await response.json();
          if (typeof raw === 'object' && raw !== null) {
            if (raw._format === 'compact' && raw.decks && raw.aliases) {
              const decks = raw.decks;
              const aliases = raw.aliases;
              const proxy = new Proxy(decks, {
                get(target, prop: string) {
                  if (prop in target) return target[prop];
                  const aliasTarget = aliases[prop];
                  if (aliasTarget && aliasTarget in target) return target[aliasTarget];
                  return (target as any)[prop];
                },
                has(target, prop: string) {
                  return (prop in target) || (prop in aliases);
                },
                ownKeys(target) {
                  return Array.from(new Set([...Object.keys(target), ...Object.keys(aliases)]));
                },
                getOwnPropertyDescriptor(target, prop: string) {
                  if (prop in target) return Object.getOwnPropertyDescriptor(target, prop);
                  if (prop in aliases) {
                    const canonical = aliases[prop];
                    if (canonical in target) {
                      return {
                        configurable: true,
                        enumerable: true,
                        writable: false,
                        value: target[canonical],
                      };
                    }
                  }
                  return undefined;
                },
              });
              this.preconDecksCache = proxy;
              return this.preconDecksCache;
            }
            this.preconDecksCache = raw;
            return this.preconDecksCache;
          }
        }
      } catch (e) {
        console.warn('Could not fetch /data/precon_decks.json:', e);
      } finally {
        this.preconDecksPromise = null;
      }
      if (!this.preconDecksCache) {
        this.preconDecksCache = {};
      }
      return this.preconDecksCache;
    })();

    return this.preconDecksPromise;
  }

