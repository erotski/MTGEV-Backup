import { SetOption, BoosterEVRecord, BoxArbitrageRecord } from '../types';
import { BoosterVariation, SheetConfig } from '../ecommerceBoosterData';

export interface DbBoosterSheet {
  sheetName: string;
  foil: boolean;
  totalWeight?: number;
  cardCount?: number;
  balanceColors?: boolean;
}

export interface DbBoosterOption {
  boosterIndex: number;
  weight: number;
  contents: Record<string, number>;
}

export interface DbBoosterData {
  boosterName: string;
  boostersTotalWeight: number;
  boosters: DbBoosterOption[];
  sheets: Record<string, DbBoosterSheet>;
}

/**
 * Converts authentic database booster records to BoosterVariation UI models.
 * Strictly preserves exact database sheet names, collation weights, and options.
 */
export function convertDbBoosterToVariations(dbBooster: DbBoosterData): BoosterVariation[] {
  const totalW = dbBooster.boostersTotalWeight || 1;
  return (dbBooster.boosters || []).map((b) => {
    const weightPct = (b.weight / totalW) * 100;
    const weightPctStr = weightPct < 0.01 ? weightPct.toExponential(2) : weightPct.toFixed(3);

    const sheets: SheetConfig[] = Object.entries(b.contents || {}).map(([sheetName, count]) => {
      const meta = dbBooster.sheets?.[sheetName];
      const isFoil = Boolean(meta?.foil || sheetName.toLowerCase().includes('foil'));
      const lower = sheetName.toLowerCase();

      let category: SheetConfig['category'] = 'special_bonus';
      if (lower.includes('common') && !lower.includes('uncommon')) category = 'common';
      else if (lower.includes('uncommon')) category = 'uncommon';
      else if (lower.includes('rare') || lower.includes('mythic')) category = 'rare_mythic';
      else if (lower.includes('land') || lower.includes('basic')) category = 'land';
      else if (lower.includes('token') || lower.includes('art') || lower.includes('ad')) category = 'ancillary';
      else if (isFoil) category = 'foil';
      else if (lower.includes('wild')) category = 'wildcard';

      return {
        sheetName: sheetName, // Strictly database sheet name!
        sheetCode: sheetName,
        sheetPicks: Number(count),
        description: `Picks: ${count} | Foil: ${isFoil ? 'Yes' : 'No'}${meta?.cardCount ? ` | Pool: ${meta.cardCount} cards` : ''}${meta?.totalWeight ? ` | Weight: ${meta.totalWeight}` : ''}`,
        category,
        foilChance: isFoil ? 1.0 : undefined,
        isSpecialSheet:
          lower.includes('serialized') ||
          lower.includes('praetor') ||
          lower.includes('mul') ||
          lower.includes('showcase') ||
          lower.includes('bonus') ||
          lower.includes('spg'),
      };
    });

    return {
      boosterIndex: b.boosterIndex,
      boosterWeight: b.weight,
      name: `Option ${b.boosterIndex}`,
      description: `Collation Option ${b.boosterIndex} (Weight: ${b.weight.toLocaleString()} / ${totalW.toLocaleString()} = ${weightPctStr}%)`,
      sheets,
    };
  });
}

export interface DataFetchStatus {
  source: 'live_pipeline' | 'empty';
  lastUpdated?: string;
  totalSets: number;
  totalProducts: number;
}

/**
 * Data Service to dynamically load JSON data generated by the Python pipeline.
 * No hardcoded mock fixtures are used.
 */
class DataService {
  private setsCache: SetOption[] | null = null;
  private arbitrageCache: BoxArbitrageRecord[] | null = null;
  private boosterEvCache: Record<string, BoosterEVRecord[]> | null = null;
  private boosterSlotsCache: Record<string, Record<string, DbBoosterData>> | null = null;
  private isLoadedFromPipeline = false;

  /**
   * Loads all sets from /data/sets.json
   */
  public async getSets(): Promise<{ sets: SetOption[]; isLive: boolean }> {
    if (this.setsCache && this.setsCache.length > 0) {
      return { sets: this.setsCache, isLive: this.isLoadedFromPipeline };
    }

    try {
      const response = await fetch('/data/sets.json', { cache: 'no-cache' });
      if (response.ok) {
        const rawSets = await response.json();
        if (Array.isArray(rawSets) && rawSets.length > 0) {
          this.setsCache = rawSets.map((s: any) => ({
            code: s.code || s.setCode,
            name: s.name,
            releaseDate: s.releaseDate || '2025-01-01',
            type: s.type || 'expansion',
            totalSetSize: s.totalSetSize || s.baseSetSize || 280,
            boosterCount: Number(s.boosterTypesCount || 2),
            boosters: ['play', 'collector'],
          }));
          this.isLoadedFromPipeline = true;
          return { sets: this.setsCache, isLive: true };
        }
      }
    } catch (e) {
      console.warn('Could not fetch /data/sets.json:', e);
    }

    this.setsCache = [];
    this.isLoadedFromPipeline = false;
    return { sets: [], isLive: false };
  }

  /**
   * Loads Arbitrage Leaderboard from /data/arbitrage_leaderboard.json
   */
  public async getArbitrageRecords(): Promise<BoxArbitrageRecord[]> {
    if (this.arbitrageCache && this.arbitrageCache.length > 0) {
      return this.arbitrageCache;
    }

    try {
      const response = await fetch('/data/arbitrage_leaderboard.json', { cache: 'no-cache' });
      if (response.ok) {
        const raw = await response.json();
        if (Array.isArray(raw) && raw.length > 0) {
          const sealedResponse = await fetch('/data/sealed_products.json', { cache: 'no-cache' });
          const sealedProducts = sealedResponse.ok ? await sealedResponse.json() : [];
          const cardCountByUuid = new Map<string, number>();
          const productsWithoutExactEv = new Set<string>();
          if (Array.isArray(sealedProducts)) {
            for (const product of sealedProducts) {
              const uuid = product.id || product.uuid;
              const rawCount = product.cardCount;
              const cardCount = rawCount !== null && rawCount !== undefined ? Number(rawCount) : NaN;
              if (uuid && Number.isFinite(cardCount) && cardCount > 0) {
                cardCountByUuid.set(uuid, cardCount);
              }
              const packCodes = Array.isArray(product.contents?.pack)
                ? product.contents.pack.map((pack: any) => String(pack.code || '').toLowerCase()).filter(Boolean)
                : [];
              const record = raw.find((item: BoxArbitrageRecord) => item.productUuid === uuid);
              if (uuid && packCodes.some((code: string) => code.includes('sample')) && record?.boosterName !== 'collector-sample') {
                productsWithoutExactEv.add(uuid);
              }
            }
          }

          this.arbitrageCache = raw.filter((record: BoxArbitrageRecord) => !productsWithoutExactEv.has(record.productUuid)).map((record: BoxArbitrageRecord) => {
            const authoritativeCardCount = cardCountByUuid.get(record.productUuid);
            const resolvedCardCount = authoritativeCardCount !== undefined && authoritativeCardCount > 0
              ? authoritativeCardCount
              : (typeof record.cardCount === 'number' && record.cardCount > 0 ? record.cardCount : undefined);
            return resolvedCardCount !== undefined
              ? { ...record, cardCount: resolvedCardCount }
              : record;
          });
          return this.arbitrageCache;
        }
      }
    } catch (e) {
      console.warn('Could not fetch /data/arbitrage_leaderboard.json:', e);
    }

    this.arbitrageCache = [];
    return [];
  }

  /**
   * Loads Booster EV calculations from /data/booster_ev.json
   */
  public async getBoosterEVs(): Promise<Record<string, BoosterEVRecord[]>> {
    if (this.boosterEvCache && Object.keys(this.boosterEvCache).length > 0) {
      return this.boosterEvCache;
    }

    try {
      const response = await fetch('/data/booster_ev.json', { cache: 'no-cache' });
      if (response.ok) {
        const rawEv = await response.json();
        if (Array.isArray(rawEv) && rawEv.length > 0) {
          const grouped: Record<string, BoosterEVRecord[]> = {};
          rawEv.forEach((item: any) => {
            const setCode = item.setCode || item.set_code;
            if (!grouped[setCode]) grouped[setCode] = [];
            grouped[setCode].push({
              id: item.id || 0,
              setCode: setCode,
              setName: item.setName || setCode,
              boosterName: item.boosterName || item.booster_name,
              fullBoosterName: `${item.boosterName} Booster`,
              priceMode: item.priceMode || item.price_mode || 'direct',
              vendor: item.vendor || 'all',
              evAverage: Number(item.evAverage || item.ev_average || 0),
              evMid90: Number(item.evMid90 || item.ev_mid90 || 0),
              evMin: Number(item.evMin || item.ev_min || 0),
              evMax: Number(item.evMax || item.ev_max || 0),
              evMin5: Number(item.evMin5 || item.ev_min5 || 0),
              evMax5: Number(item.evMax5 || item.ev_max5 || 0),
              quantiles: Array.isArray(item.quantiles) && item.quantiles.length > 0 ? item.quantiles.map(Number) : undefined,
              completeBoosterPct: Number(item.completeBoosterPct || item.complete_booster_pct || 100),
              exactMatchPct: Number(item.exactMatchPct || item.exact_match_pct || 100),
              differentFinishPct: Number(item.differentFinishPct || item.different_finish_pct || 0),
              differentVendorPct: Number(item.differentVendorPct || item.different_vendor_pct || 0),
              failedBoosters: Number(item.failedBoosters || item.failed_boosters || 0),
              simulatedPacks: Number(item.simulatedPacks || item.simulated_packs || 5000),
              updatedAt: item.updatedAt || item.updated_at || new Date().toISOString(),
            });
          });
          this.boosterEvCache = grouped;
          return this.boosterEvCache;
        }
      }
    } catch (e) {
      console.warn('Could not fetch /data/booster_ev.json:', e);
    }

    this.boosterEvCache = {};
    return {};
  }

  /**
   * Loads Preconstructed Decks from /data/precon_decks.json
   */
  public async getPreconDecks(): Promise<Record<string, any>> {
    try {
      const response = await fetch('/data/precon_decks.json', { cache: 'no-cache' });
      if (response.ok) {
        const raw = await response.json();
        if (typeof raw === 'object' && raw !== null) {
          return raw;
        }
      }
    } catch (e) {
      console.warn('Could not fetch /data/precon_decks.json:', e);
    }
    return {};
  }

  /**
   * Loads raw sealed products with contents column from /data/sealed_products.json
   */
  public async getSealedProducts(): Promise<any[]> {
    try {
      const response = await fetch('/data/sealed_products.json', { cache: 'no-cache' });
      if (response.ok) {
        const raw = await response.json();
        if (Array.isArray(raw)) {
          return raw;
        }
      }
    } catch (e) {
      console.warn('Could not fetch /data/sealed_products.json:', e);
    }
    return [];
  }

  /**
   * Loads individual card pricing & EV index from /data/single_card_prices.json
   */
  public async getSingleCardPrices(): Promise<{
    byUuid: Record<string, any>;
    byNameSet: Record<string, any>;
    byName: Record<string, any>;
    totalIndexed: number;
  }> {
    try {
      const response = await fetch('/data/single_card_prices.json', { cache: 'no-cache' });
      if (response.ok) {
        const raw = await response.json();
        if (raw && typeof raw === 'object') {
          return raw;
        }
      }
    } catch (e) {
      console.warn('Could not fetch /data/single_card_prices.json:', e);
    }
    return { byUuid: {}, byNameSet: {}, byName: {}, totalIndexed: 0 };
  }

  /**
   * Loads all booster slot collation definitions for a given set.
   * Uses authentic MTGJSON database structure (setBoosterContentWeights, setBoosterContents, setBoosterSheets).
   */
  public async getAllBoosterSlotsForSet(setCode: string): Promise<Record<string, DbBoosterData> | null> {
    const upperCode = (setCode || '').toUpperCase().trim();
    if (!upperCode) return null;

    // Load /data/booster_slots.json once
    if (!this.boosterSlotsCache) {
      try {
        const response = await fetch('/data/booster_slots.json');
        if (response.ok) {
          const raw = await response.json();
          this.boosterSlotsCache = raw;
        }
      } catch (e) {
        console.warn('Could not load /data/booster_slots.json:', e);
      }
      if (!this.boosterSlotsCache) {
        this.boosterSlotsCache = {};
      }
    }

    // Check if set is in cache
    if (this.boosterSlotsCache[upperCode]) {
      return this.boosterSlotsCache[upperCode];
    }

    // On-demand fetch from MTGJSON API if set not yet in local JSON
    try {
      const res = await fetch(`https://mtgjson.com/api/v5/${upperCode}.json`);
      if (res.ok) {
        const json = await res.json();
        const boosterObj = json.data?.booster;
        if (boosterObj) {
          const formatted: Record<string, DbBoosterData> = {};
          for (const [bName, bInfo] of Object.entries<any>(boosterObj)) {
            formatted[bName] = {
              boosterName: bName,
              boostersTotalWeight: Number(bInfo.boostersTotalWeight || 0),
              boosters: (bInfo.boosters || []).map((b: any, idx: number) => ({
                boosterIndex: idx,
                weight: Number(b.weight || 0),
                contents: b.contents || {},
              })),
              sheets: Object.fromEntries(
                Object.entries<any>(bInfo.sheets || {}).map(([sName, sData]) => [
                  sName,
                  {
                    sheetName: sName,
                    foil: Boolean(sData.foil),
                    totalWeight: sData.totalWeight ? Number(sData.totalWeight) : undefined,
                    cardCount: sData.cards ? Object.keys(sData.cards).length : undefined,
                    balanceColors: Boolean(sData.balanceColors),
                  },
                ])
              ),
            };
          }
          this.boosterSlotsCache[upperCode] = formatted;
          return formatted;
        }
      }
    } catch (e) {
      console.warn(`Could not fetch booster slots for set ${upperCode}:`, e);
    }

    return null;
  }

  /**
   * Retrieves the specific booster slot configuration (e.g. 'collector', 'play', 'draft') for a product.
   * In MOM Collector Booster, this strictly returns all 24 collation variations with authentic MTGJSON sheets.
   */
  public async getBoosterSlots(
    setCode: string,
    boosterType?: string,
    productName?: string
  ): Promise<DbBoosterData | null> {
    const setBoosters = await this.getAllBoosterSlotsForSet(setCode);
    if (!setBoosters || Object.keys(setBoosters).length === 0) {
      return null;
    }

    const availableTypes = Object.keys(setBoosters);
    const searchTarget = `${boosterType || ''} ${productName || ''}`.toLowerCase();

    // 1. Direct type match
    if (boosterType && setBoosters[boosterType]) {
      return setBoosters[boosterType];
    }

    // 2. Infer booster type from product naming
    if (searchTarget.includes('collector-sample') || searchTarget.includes('sample')) {
      if (setBoosters['collector-sample']) return setBoosters['collector-sample'];
    }
    if (searchTarget.includes('collector')) {
      if (setBoosters['collector']) return setBoosters['collector'];
    }
    if (searchTarget.includes('play')) {
      if (setBoosters['play']) return setBoosters['play'];
    }
    if (searchTarget.includes('draft')) {
      if (setBoosters['draft']) return setBoosters['draft'];
    }
    if (searchTarget.includes('set booster') || searchTarget.includes('set-booster')) {
      if (setBoosters['set']) return setBoosters['set'];
    }
    if (searchTarget.includes('jumpstart')) {
      if (setBoosters['jumpstart']) return setBoosters['jumpstart'];
    }
    if (searchTarget.includes('prerelease')) {
      if (setBoosters['prerelease']) return setBoosters['prerelease'];
    }

    // 3. Match any key contained in searchTarget
    for (const type of availableTypes) {
      if (searchTarget.includes(type)) {
        return setBoosters[type];
      }
    }

    // 4. Default fallbacks in order of preference: play, draft, collector, set, first available
    if (setBoosters['play']) return setBoosters['play'];
    if (setBoosters['draft']) return setBoosters['draft'];
    if (setBoosters['collector']) return setBoosters['collector'];
    if (setBoosters['set']) return setBoosters['set'];
    return setBoosters[availableTypes[0]] || null;
  }
}

export const dataService = new DataService();
